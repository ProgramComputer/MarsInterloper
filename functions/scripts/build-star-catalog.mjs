// Builds src/bright-stars.js from the Hipparcos catalog in assets/mars_data.
//
// The full CSV is 38MB, far too much to parse inside a Worker request, so the Worker bundles
// just the naked-eye stars (V <= 6.5, the same cut cmd/server/mars_sky.go uses).
//
// Usage: node scripts/build-star-catalog.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CATALOG = fileURLToPath(new URL("../../assets/mars_data/hipparcos-voidmain.csv", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../src/bright-stars.js", import.meta.url));
const MAX_MAGNITUDE = 6.5;

// Same palette and thresholds as getBVColor in cmd/server/mars_sky.go.
const COLORS = ["#FFFFFF", "#9BB0FF", "#AAC0FF", "#CAD7FF", "#F8F7FF", "#FFF4EA", "#FFD2A1", "#FFCC6F"];
const SPECTRAL_COLOR = { O: 1, B: 2, A: 3, F: 4, G: 5, K: 6, M: 7 };

function colorIndex(bv, spectralType) {
	if (bv === 0) return SPECTRAL_COLOR[spectralType[0]] ?? 0;
	if (bv < -0.3) return 1;
	if (bv < 0.0) return 2;
	if (bv < 0.3) return 3;
	if (bv < 0.6) return 4;
	if (bv < 1.0) return 5;
	if (bv < 1.5) return 6;
	return 7;
}

const num = (s) => (s.trim() === "" ? NaN : Number(s));

const stars = [];
const lines = readFileSync(CATALOG, "utf8").split(/\r?\n/);
for (const line of lines.slice(1)) {
	const f = line.split(",");
	if (f.length < 77) continue;
	const hip = num(f[1]);
	const ra = num(f[8]);
	const dec = num(f[9]);
	let vmag = num(f[5]);
	if (Number.isNaN(vmag)) vmag = num(f[44]); // Hipparcos magnitude when V is missing
	if (![hip, ra, dec, vmag].every(Number.isFinite) || vmag > MAX_MAGNITUDE) continue;
	const bv = num(f[37]);
	stars.push({ hip, ra, dec, vmag, color: colorIndex(Number.isNaN(bv) ? 0 : bv, f[76].trim()) });
}
stars.sort((a, b) => a.vmag - b.vmag || a.hip - b.hip);

const rows = stars.map((s) => `${s.hip},${s.ra.toFixed(4)},${s.dec.toFixed(4)},${s.vmag.toFixed(2)},${s.color}`);
writeFileSync(
	OUTPUT,
	`// Generated by scripts/build-star-catalog.mjs from assets/mars_data/hipparcos-voidmain.csv. Do not edit.\n` +
		`// ${stars.length} Hipparcos stars with V <= ${MAX_MAGNITUDE}, brightest first.\n\n` +
		`export const STAR_COLORS = ${JSON.stringify(COLORS)};\n\n` +
		`// Flat rows of [HIP, RA (deg, ICRS), Dec (deg, ICRS), V magnitude, STAR_COLORS index].\n` +
		`export const BRIGHT_STARS = [\n${rows.join(",\n")},\n];\n`,
);
console.log(`Wrote ${stars.length} stars to ${OUTPUT}`);
